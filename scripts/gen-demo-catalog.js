/** Emits a browser-safe copy of the catalog so demo builds need no server. */
import { writeFile } from 'node:fs/promises';
import { entities } from '../server/catalog/entities.js';

const out = entities.map((e) => ({
  key: e.key, table_name: e.table, label: e.label, label_plural: e.label_plural,
  icon: e.icon, nav_group: e.nav_group, sort_order: e.sort_order,
  default_sort: e.default_sort, title_column: e.title_column,
  search_columns: e.search_columns, fields: e.fields,
}));

await writeFile(
  new URL('../web/src/lib/catalog-demo.js', import.meta.url),
  `// generated by scripts/gen-demo-catalog.js — do not edit\nexport const catalog = ${JSON.stringify(out, null, 2)};\n`
);
console.log(`wrote catalog-demo.js (${out.length} entities)`);
